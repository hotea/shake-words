/** 随机取一首诗 */
export function getRandomPoem(excludeIds: string[] = []): Poem {
  const available = POEMS.filter((p) => !excludeIds.includes(p.id));
  const pool = available.length > 0 ? available : POEMS;
  return pool[Math.floor(Math.random() * pool.length)];
}
